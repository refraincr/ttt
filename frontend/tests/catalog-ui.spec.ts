import { test, expect } from '@playwright/test'
import { demoPassword, uniqueName } from './support'

test('配置查询支持关键词、类型、状态组合，重置及切换标签恢复列表', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('textbox', { name: '账号', exact: true }).fill('admin')
  await page.getByRole('textbox', { name: '密码', exact: true }).fill(demoPassword)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('button', { name: '来源与分类', exact: true }).click()
  const panel = page.getByRole('tabpanel', { name: '数据来源', exact: true })
  await expect(panel.getByRole('row').filter({ hasText: '部门上报' }).first()).toBeVisible()
  await panel.getByRole('textbox', { name: '查找来源' }).fill('部门上报')
  await panel.getByRole('combobox', { name: '筛选配置类型' }).press('ArrowDown')
  await page.getByRole('option', { name: '部门上报', exact: true }).click()
  await panel.getByRole('combobox', { name: '筛选启用状态' }).press('ArrowDown')
  await page.getByRole('option', { name: '启用', exact: true }).click()
  await panel.getByRole('button', { name: '查询', exact: true }).click()
  await expect(panel.locator('.el-table__body-wrapper tbody tr')).toHaveCount(1)
  await expect(panel.getByRole('row').filter({ hasText: '部门上报' })).toContainText('启用')
  await panel.getByRole('textbox', { name: '查找来源' }).fill(uniqueName('不存在'))
  await panel.getByRole('textbox', { name: '查找来源' }).press('Enter')
  await expect(panel.getByText('没有符合条件的来源，请调整查询条件')).toBeVisible()
  await panel.getByRole('button', { name: '重置', exact: true }).click()
  await expect(panel.getByRole('textbox', { name: '查找来源' })).toHaveValue('')
  await expect(panel.getByRole('row').filter({ hasText: '部门上报' }).first()).toBeVisible()
  await panel.getByRole('textbox', { name: '查找来源' }).fill('不应带入分类')
  await page.getByRole('tab', { name: '标准分类' }).click()
  const categories = page.getByRole('tabpanel', { name: '标准分类', exact: true })
  await expect(categories.getByRole('textbox', { name: '查找分类' })).toHaveValue('')
  await categories.getByRole('textbox', { name: '查找分类' }).fill('livelihood')
  await categories.getByRole('textbox', { name: '查找分类' }).press('Enter')
  await expect(categories.locator('.el-table__body-wrapper tbody tr')).toHaveCount(1)
  await expect(categories.getByRole('row').filter({ hasText: 'LIVELIHOOD' })).toContainText('民生诉求')
  await categories.getByRole('button', { name: '编辑分类LIVELIHOOD', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('textbox', { name: '分类编码', exact: true })).toBeDisabled()
  await expect(dialog.getByRole('combobox', { name: '字典类别', exact: true })).toBeDisabled()
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
})

test('页面维护来源与纠纷类型，停用后业务账号不再看到可选项', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('textbox', { name: '账号', exact: true }).fill('admin')
  await page.getByRole('textbox', { name: '密码', exact: true }).fill(demoPassword)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('button', { name: '来源与分类', exact: true }).click()
  await page.getByRole('button', { name: '新增来源', exact: true }).click()
  const sourceName = uniqueName('页面来源')
  await page.getByRole('textbox', { name: '来源名称', exact: true }).fill(sourceName)
  await page.getByRole('button', { name: '保存来源', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: sourceName })).toBeVisible()
  await page.getByRole('button', { name: `编辑来源${sourceName}`, exact: true }).click()
  await page.getByRole('switch', { name: '来源启用', exact: true }).locator('..').click()
  await page.getByRole('button', { name: '保存来源', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: sourceName })).toContainText('停用')
  await page.getByRole('tab', { name: '标准分类' }).click()
  await page.getByRole('button', { name: '新增标准分类', exact: true }).click()
  const code = uniqueName('UI_CODE')
  const dictionaryName = uniqueName('页面纠纷')
  await page.getByRole('combobox', { name: '字典类别', exact: true }).press('ArrowDown')
  await page.getByRole('option', { name: '纠纷类型', exact: true }).click()
  await page.getByRole('textbox', { name: '分类编码', exact: true }).fill(code)
  await page.getByRole('textbox', { name: '分类名称', exact: true }).fill(dictionaryName)
  await page.getByRole('button', { name: '保存标准分类', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: code })).toContainText('纠纷类型')
  await page.reload()
  await page.getByRole('button', { name: '来源与分类', exact: true }).click()
  await page.getByRole('tab', { name: '标准分类' }).click()
  await expect(page.getByRole('row').filter({ hasText: code })).toContainText(dictionaryName)
  await page.screenshot({ path: 'test-results/catalog-management.png', fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: '退出登录', exact: true }).click()
  await page.getByRole('textbox', { name: '账号', exact: true }).fill('civil')
  await page.getByRole('textbox', { name: '密码', exact: true }).fill(demoPassword)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('button', { name: '部门与账号', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '来源与分类', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: sourceName })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '新增来源', exact: true })).toHaveCount(0)
  await page.getByRole('tab', { name: '标准分类' }).click()
  await expect(page.getByRole('row').filter({ hasText: code })).toBeVisible()
})
