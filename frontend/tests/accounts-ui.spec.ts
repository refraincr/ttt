import { test, expect } from '@playwright/test'
import { demoPassword, uniqueName } from './support'

test('管理员通过页面创建部门和兼任账号，刷新后保留，可停用账号', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('textbox', { name: '账号', exact: true }).fill('admin')
  await page.getByRole('textbox', { name: '密码', exact: true }).fill(demoPassword)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('button', { name: '部门与账号', exact: true }).click()
  await expect(page.getByRole('heading', { name: '部门与账号' })).toBeVisible()
  await page.getByRole('tab', { name: '部门管理' }).click()
  await page.getByRole('button', { name: '新增部门', exact: true }).click()
  const department = uniqueName('页面部门')
  await page.getByRole('textbox', { name: '部门名称', exact: true }).fill(department)
  await page.getByRole('button', { name: '保存部门', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: department })).toBeVisible()
  await page.getByRole('tab', { name: '账号管理' }).click()
  await page.getByRole('button', { name: '新增账号', exact: true }).click()
  const username = uniqueName('ui')
  await page.getByRole('textbox', { name: '登录账号', exact: true }).fill(username)
  await page.getByRole('textbox', { name: '姓名', exact: true }).fill('页面兼任员')
  await page.getByRole('combobox', { name: '归属部门', exact: true }).click()
  await page.getByRole('option', { name: department, exact: true }).click()
  await page.getByText('部门上报', { exact: true }).last().click()
  await page.getByText('部门处置', { exact: true }).last().click()
  await expect(page.getByRole('checkbox', { name: '部门处置', exact: true })).toBeChecked()
  await page.getByRole('textbox', { name: '账号密码', exact: true }).fill('Interface-Test-2026!')
  await page.getByRole('button', { name: '保存账号', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: username })).toContainText('部门处置')
  await page.reload()
  await page.getByRole('button', { name: '部门与账号', exact: true }).click()
  await page.getByRole('button', { name: `编辑账号${username}`, exact: true }).click()
  await page.getByRole('switch', { name: '账号启用', exact: true }).locator('..').click()
  await page.getByRole('button', { name: '保存账号', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: username })).toContainText('停用')
  await page.screenshot({ path: 'test-results/account-management.png', fullPage: true, animations: 'disabled' })
})
