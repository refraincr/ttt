CREATE TABLE tb_keyword_exclusion (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, event_id BIGINT NOT NULL, rule_id BIGINT NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE, fingerprint CHAR(64) NOT NULL, reason VARCHAR(1000) NOT NULL, actor VARCHAR(100) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE tb_risk_adjustment (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, person_id BIGINT NOT NULL, level VARCHAR(10) NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE, fingerprint CHAR(64) NOT NULL, reason VARCHAR(1000) NOT NULL, actor VARCHAR(100) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE tb_rule_release (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, payload JSON NOT NULL, state VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
 version BIGINT NOT NULL DEFAULT 1, actor VARCHAR(100) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE tb_rule_preview (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, release_id BIGINT NOT NULL, draft_version BIGINT NOT NULL,
 evidence JSON NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE tb_risk_history (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, person_id BIGINT NOT NULL, snapshot JSON NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE tb_risk_notification (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, person_id BIGINT NOT NULL, before_level VARCHAR(10),
 after_level VARCHAR(10) NOT NULL, history_id BIGINT NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE tb_recalculation (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, release_id BIGINT NOT NULL, state VARCHAR(20) NOT NULL DEFAULT 'PENDING',
 completed BIGINT NOT NULL DEFAULT 0, total BIGINT NOT NULL DEFAULT 0, error TEXT,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
