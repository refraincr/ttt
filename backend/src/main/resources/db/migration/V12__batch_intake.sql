CREATE TABLE tb_source_mapping (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, source_id BIGINT NOT NULL, name VARCHAR(100) NOT NULL,
 payload JSON NOT NULL, version BIGINT NOT NULL DEFAULT 1, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE tb_external_credential (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, token_hash CHAR(64) NOT NULL UNIQUE, department_id BIGINT NOT NULL,
 source_id BIGINT NOT NULL, special_report BOOLEAN NOT NULL, enabled BOOLEAN NOT NULL DEFAULT TRUE,
 owner_id BIGINT NOT NULL, name VARCHAR(100) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE tb_import_batch (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, owner_id BIGINT NOT NULL, username VARCHAR(100) NOT NULL,
 source_id BIGINT NOT NULL, mapping_snapshot JSON, original_file LONGBLOB, filename VARCHAR(255),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE tb_import_row (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, batch_id BIGINT NOT NULL, line_number INT NOT NULL, payload JSON NOT NULL,
 state VARCHAR(20) NOT NULL DEFAULT 'PENDING', error TEXT, record_id BIGINT, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE tb_intake_receipt (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, scope VARCHAR(100) NOT NULL, external_key CHAR(64) NOT NULL,
 record_id BIGINT NOT NULL, UNIQUE KEY(scope,external_key)
);
CREATE TABLE tb_external_receipt (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, credential_id BIGINT NOT NULL, external_id VARCHAR(200),
 payload JSON NOT NULL, record_id BIGINT, error TEXT, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
