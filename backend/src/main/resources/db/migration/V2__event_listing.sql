-- 原 29 字段以用户于 2026-10-17 提供的 SQL 为准，保留类型、默认值及索引。
-- 此迁移用于新库；现有业务库必须先单独建立 Flyway 基线，不可直接套用。
CREATE TABLE tb_input_record (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    occurred_at DATETIME NOT NULL,
    problem_description TEXT NOT NULL,
    party_name VARCHAR(100) DEFAULT NULL,
    party_id_card VARCHAR(50) DEFAULT NULL,
    party_phone VARCHAR(32) DEFAULT NULL,
    party_address VARCHAR(500) DEFAULT NULL,
    handler_name VARCHAR(100) DEFAULT NULL,
    handling_description TEXT DEFAULT NULL,
    event_category VARCHAR(100) NOT NULL,
    dispute_type VARCHAR(100) NOT NULL,
    event_source VARCHAR(100) NOT NULL,
    handling_deadline DATETIME DEFAULT NULL,
    remark TEXT DEFAULT NULL,
    matched_person_id BIGINT UNSIGNED NULL,
    matched_at DATETIME NULL,
    match_status TINYINT UNSIGNED NOT NULL DEFAULT 0,
    review_status TINYINT UNSIGNED NOT NULL DEFAULT 0,
    keyword_tags VARCHAR(500) NULL,
    event_risk_level VARCHAR(16) NULL,
    storage_path VARCHAR(500) NULL,
    error_path VARCHAR(500) NULL,
    is_completed TINYINT UNSIGNED NOT NULL DEFAULT 0,
    gmt_create DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    gmt_modified DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    created_by VARCHAR(50) NOT NULL,
    modified_by VARCHAR(50) NOT NULL,
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT 0,
    version INT UNSIGNED NOT NULL DEFAULT 1,
    department_id BIGINT UNSIGNED NOT NULL,
    identity_review_state VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    duplicate_review_state VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    CONSTRAINT fk_record_department FOREIGN KEY (department_id) REFERENCES tb_department(id),
    KEY idx_occurred_at (occurred_at),
    KEY idx_deadline_done (is_completed, handling_deadline),
    KEY idx_party_id_card (party_id_card),
    KEY idx_party_phone (party_phone),
    KEY idx_match_status (match_status, matched_person_id),
    KEY idx_category_dispute (event_category, dispute_type),
    INDEX idx_record_department_time (department_id, is_deleted, occurred_at, id),
    INDEX idx_record_time (is_deleted, occurred_at, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='纠纷事件记录主表';
