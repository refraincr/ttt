CREATE TABLE tb_event_draft (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 owner_id BIGINT UNSIGNED NOT NULL, payload JSON NOT NULL,
 version BIGINT NOT NULL DEFAULT 1, record_id BIGINT UNSIGNED NULL
);
CREATE TABLE tb_person (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL, id_card VARCHAR(18) NULL UNIQUE, phone VARCHAR(32) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE tb_record_provenance (
 record_id BIGINT UNSIGNED PRIMARY KEY, draft_id BIGINT UNSIGNED NOT NULL UNIQUE,
 original_payload JSON NOT NULL, source_id BIGINT UNSIGNED NOT NULL,
 category_id BIGINT UNSIGNED NOT NULL, dispute_id BIGINT UNSIGNED NOT NULL,
 special_report BOOLEAN NOT NULL, actor_id BIGINT UNSIGNED NOT NULL,
 FOREIGN KEY(record_id) REFERENCES tb_input_record(id)
);
CREATE TABLE tb_duplicate_settings (
 id INT PRIMARY KEY, window_days INT NOT NULL, threshold DOUBLE NOT NULL, version BIGINT NOT NULL DEFAULT 1
);
