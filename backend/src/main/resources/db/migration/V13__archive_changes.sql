ALTER TABLE tb_person ADD COLUMN version BIGINT NOT NULL DEFAULT 1,
 ADD COLUMN merged_into BIGINT UNSIGNED NULL;
CREATE TABLE tb_record_change (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 record_id BIGINT UNSIGNED NOT NULL,
 record_version BIGINT NOT NULL,
 kind VARCHAR(16) NOT NULL,
 payload JSON NULL,
 before_data JSON NOT NULL,
 after_data JSON NULL,
 reason VARCHAR(1000) NOT NULL,
 state VARCHAR(16) NOT NULL DEFAULT 'PENDING',
 requester VARCHAR(100) NOT NULL,
 reviewer VARCHAR(100) NULL,
 review_reason VARCHAR(1000) NULL,
 department_id BIGINT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 reviewed_at DATETIME NULL
);
CREATE TABLE tb_archive_change (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 kind VARCHAR(16) NOT NULL,
 from_person_id BIGINT UNSIGNED NOT NULL,
 to_person_id BIGINT UNSIGNED NOT NULL,
 record_id BIGINT UNSIGNED NULL,
 reason VARCHAR(1000) NOT NULL,
 actor VARCHAR(100) NOT NULL,
 before_data JSON NOT NULL,
 after_data JSON NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
